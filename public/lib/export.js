// Walk export: a self-contained HTML file with inline base64 images - the
// keepsake. Pure: takes data, returns strings. No DOM, no storage.

import { unreachableRate } from './proximity.js';
import { formatDistance } from './geo.js';
import { BASE_CSS, PRINT_CSS } from './skins.js';

/**
 * The app icon as a hand-authored vector, matching icons/icon-master.png
 * (dark green field, three cream waypoints, one green origin, orange dashed
 * legs). Inlined into exports as a data URI so the keepsake needs no network.
 */
export const ICON_SVG = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><rect width="1024" height="1024" fill="#12201b"/><path d="M348 520 L480 556 L600 405 M480 556 L685 615" fill="none" stroke="#ffb43d" stroke-width="26" stroke-dasharray="46 40"/><ellipse cx="295" cy="512" rx="68" ry="62" fill="#ede4d4" transform="rotate(-28 295 512)"/><circle cx="349" cy="673" r="66" fill="#5fa98d"/><ellipse cx="615" cy="350" rx="74" ry="64" fill="#ede4d4" transform="rotate(-18 615 350)"/><circle cx="727" cy="619" r="66" fill="#ede4d4"/></svg>`;

export const ICON_DATA_URI = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(ICON_SVG)}`;

/**
 * Convert a blob to a base64 data URL.
 */
export function blobToDataURL(blob) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(reader.error);
    reader.readAsDataURL(blob);
  });
}

/**
 * Build a self-contained HTML document for a walk.
 * @param {object} walk  The walk record from IndexedDB.
 * @param {Array} photos Array of { stopSeq, dataUrl?, blob? } for this walk.
 * @param {string} svgTrace  Pre-rendered SVG string of the trace.
 * @param {string} [skinCss]  Optional skin CSS fragment (lib/skins.js),
 *   embedded after the base styles. CSS only - no scripts, ever.
 */
export async function buildHTMLExport(walk, photos, svgTrace, skinCss = '') {
  const photoMap = new Map();
  for (const p of photos) photoMap.set(p.stopSeq, p);

  const photoDataUrls = new Map();
  for (const [seq, p] of photoMap) {
    if (p.dataUrl) {
      photoDataUrls.set(seq, p.dataUrl);
    } else if (p.blob) {
      try {
        photoDataUrls.set(seq, await blobToDataURL(p.blob));
      } catch {
        // Legacy IndexedDB blob unreadable (WebKit corrupts stored blobs
        // after a restart) - export the walk without this photo.
      }
    }
  }

  const date = walk.started ? new Date(walk.started).toLocaleString() : 'Unknown date';
  const unreachable = unreachableRate(walk.stops);
  const reached = walk.stops.filter((s) => s.reachedAt).length;

  const stopCards = walk.stops.map((s, i) => {
    const photoUrl = photoDataUrls.get(s.seq);
    const photoHtml = photoUrl
      ? `<img src="${photoUrl}" style="max-width:100%;border-radius:8px;margin-top:8px;">`
      : '';
    const status = s.approached
      ? '<span class="status approached">close as I can get</span>'
      : s.reachedAt
        ? '<span class="status reached">reached</span>'
        : '<span class="status missed">not reached</span>';
    // Inner stops carry the hexagram resolved from their coordinates.
    const hex = s.hexagram;
    const hexHtml = hex
      ? `<div class="card-hex"><span class="glyph">${hex.glyph}</span><span class="hex-meta"><span class="hex-num">Hexagram ${hex.number}</span><span class="hex-title">${hex.title}</span></span></div>`
      : '';
    return `<div class="stop">
      <div class="stop-num">${i + 1}</div>
      <div class="stop-body">
        <div class="stop-meta">${status}</div>
        ${hexHtml}
        <div class="card-text${hex ? ' card-haiku' : ''}">${s.cardText || ''}</div>
        ${photoHtml}
      </div>
    </div>`;
  }).join('\n');

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Aimless — Walk ${walk.seed}</title>
<style>
${BASE_CSS}
@media print {
${PRINT_CSS}
}
</style>
${skinCss ? `<style id="skin">\n${skinCss}\n</style>` : ''}
</head>
<body>
  <h1><img class="app-icon" src="${ICON_DATA_URI}" alt="">Aimless</h1>
  <div class="seed">${walk.seed}</div>
  <div class="date">${date}</div>
  <div class="summary">
    <b>${reached}</b> of ${walk.stops.length} stops reached.
    ${unreachable.approached > 0 ? `<b>${unreachable.approached}</b> marked "close as I can get" (${Math.round(unreachable.rate * 100)}%).` : ''}
    ${walk.gaveUp ? '<br>Walk ended early.' : ''}
  </div>
  <div class="trace">${svgTrace}</div>
  ${stopCards}
  <footer>Generated by <a href="https://aimless.earth">Aimless</a>. This file is self-contained — no network needed.</footer>
</body>
</html>`;
}

/**
 * Trigger a download in the browser.
 */
export function downloadFile(filename, content, mimeType) {
  const blob = content instanceof Blob ? content : new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
